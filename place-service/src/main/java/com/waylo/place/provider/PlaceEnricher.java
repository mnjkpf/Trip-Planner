package com.waylo.place.provider;

/**
 * Абстракція над джерелом «деталей» місця (фото тощо). Окрема від PlacesProvider:
 * пошук POI і збагачення однієї точки — різні задачі, і провайдери можуть відрізнятись.
 * Реалізація має деградувати мʼяко: нічого не знайшли / сервіс недоступний — повертає null.
 */
public interface PlaceEnricher {

    /** Чи налаштований провайдер. Якщо ні — збагачення взагалі не пробуємо. */
    boolean isEnabled();

    /**
     * Шукає фото для місця за його назвою. null — якщо нічого не знайшли
     * (немає статті, стаття неоднозначна, або сервіс недоступний).
     */
    PlaceImage fetchImage(String name);
}
